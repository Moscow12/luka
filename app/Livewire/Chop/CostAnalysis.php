<?php

namespace App\Livewire\Chop;

use App\Exports\Chop\CostAnalysisExport;
use App\Exports\Chop\CostAnalysisSheet;
use App\Exports\EngineeringTableExport;
use App\Http\Controllers\Chop\ChopReportPdfController;
use App\Models\chopactivities;
use App\Models\chopcategoryarea;
use App\Models\FinancialYear;
use App\Models\sourceoffunds;
use App\Reports\Chop\CostAnalysisReport;
use Illuminate\Support\Facades\Auth;
use Livewire\Component;
use Livewire\WithPagination;
use Maatwebsite\Excel\Facades\Excel;

class CostAnalysis extends Component
{
    use WithPagination;

    public $search = '';

    public $filterFinancialYear = '';

    public $filterCategory = '';

    public $filterActivityType = '';

    public $filterSource = '';

    public $expandedActivity = null;

    public function mount()
    {
        // Set default to current financial year
        $currentFY = FinancialYear::current();
        if ($currentFY) {
            $this->filterFinancialYear = $currentFY->id;
        }
    }

    public function toggleActivity($activityId)
    {
        if ($this->expandedActivity === $activityId) {
            $this->expandedActivity = null;
        } else {
            $this->expandedActivity = $activityId;
        }
    }

    public function updating($property)
    {
        if (in_array($property, ['search', 'filterFinancialYear', 'filterCategory', 'filterActivityType', 'filterSource'], true)) {
            $this->resetPage();
        }
    }

    protected function report(): CostAnalysisReport
    {
        return new CostAnalysisReport(
            $this->search,
            $this->filterFinancialYear ?: null,
            $this->filterCategory ?: null,
            $this->filterActivityType ?: null,
            $this->filterSource ?: null,
        );
    }

    protected function authorizeExport(): void
    {
        $user = Auth::user();
        abort_unless($user && ($user->isSuperAdmin() || $user->can('manage-chop')), 403);
    }

    public function exportExcel()
    {
        $this->authorizeExport();
        $report = $this->report();
        $activities = $report->activities();
        [$headings, $rows, $fills] = $report->excelTable($activities);

        $meta = collect($report->filterSummary())->filter()->map(fn ($value, $label) => "{$label}: {$value}")->values()->all();
        $meta[] = 'Generated by '.trim(Auth::user()->first_name.' '.Auth::user()->surname).' on '.now()->format('d M Y H:i');

        return Excel::download(
            new CostAnalysisExport(
                new CostAnalysisSheet($report->sheet($activities), $report->sheetTitle(), $meta),
                new EngineeringTableExport('Planned vs Actual Variance', $headings, $rows, $meta, $fills),
            ),
            'chop-cost-analysis-'.now()->format('Ymd-His').'.xlsx'
        );
    }

    public function exportPdf()
    {
        $this->authorizeExport();

        return ChopReportPdfController::costAnalysisPdf($this->report())->download('chop-cost-analysis-'.now()->format('Ymd'));
    }

    public function render()
    {
        $report = $this->report();

        $activities = $report->query()->paginate(15);
        CostAnalysisReport::withCosts($activities);

        return view('livewire.chop.cost-analysis', [
            'activities' => $activities,
            'financialYears' => FinancialYear::active()->orderBy('start_date', 'desc')->get(),
            'categories' => chopcategoryarea::orderBy('name')->get(),
            'activityTypes' => chopactivities::getActivityTypes(),
            'sources' => sourceoffunds::orderBy('name')->get(),
            // Totals over every matching activity, not only this page
            'stats' => $report->stats(),
            'pdfFilters' => $report->toArray(),
        ]);
    }
}
