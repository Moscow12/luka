<?php

namespace App\Livewire\Chop;

use App\Exports\EngineeringTableExport;
use App\Http\Controllers\Chop\ChopReportPdfController;
use App\Models\chopactivities;
use App\Models\chopcategoryarea;
use App\Models\FinancialYear;
use App\Reports\Chop\MonitoringReport;
use Illuminate\Support\Facades\Auth;
use Livewire\Component;
use Livewire\WithPagination;
use Maatwebsite\Excel\Facades\Excel;

class MonitoringEvaluation extends Component
{
    use WithPagination;

    public $search = '';

    public $filterFinancialYear = '';

    public $filterCategory = '';

    public $selectedActivity = null;

    public $showActivityDetail = false;

    public function mount()
    {
        // Set default to current financial year
        $currentFY = FinancialYear::current();
        if ($currentFY) {
            $this->filterFinancialYear = $currentFY->id;
        }
    }

    public function viewActivityDetail($activityId)
    {
        $this->selectedActivity = chopactivities::with(['category', 'source', 'financialYear', 'personels.title', 'items.item'])
            ->findOrFail($activityId);
        $this->showActivityDetail = true;
    }

    public function closeActivityDetail()
    {
        $this->showActivityDetail = false;
        $this->selectedActivity = null;
    }

    public function updating($property)
    {
        if (in_array($property, ['search', 'filterFinancialYear', 'filterCategory'], true)) {
            $this->resetPage();
        }
    }

    protected function report(): MonitoringReport
    {
        return new MonitoringReport($this->search, $this->filterFinancialYear ?: null, $this->filterCategory ?: null);
    }

    public function shouldMonitorInMonth($activity, $monthNumber)
    {
        return MonitoringReport::shouldMonitorInMonth($activity, (int) $monthNumber);
    }

    /** Uses the eager-loaded reports instead of a query per calendar cell. */
    public function getReportForActivityMonth($activity, $monthYear)
    {
        return MonitoringReport::reportFor($activity, $monthYear);
    }

    protected function authorizeExport(): void
    {
        $user = Auth::user();
        abort_unless($user && ($user->isSuperAdmin() || $user->can('manage-chop')), 403);
    }

    public function exportExcel()
    {
        $this->authorizeExport();
        $report = $this->report();
        $months = MonitoringReport::months($report->financialYear());
        [$headings, $rows, $fills] = $report->excelTable($report->activities(), $months);

        $meta = collect($report->filterSummary())->filter()->map(fn ($value, $label) => "{$label}: {$value}")->values()->all();
        $meta[] = 'Legend: Done = completed, Partial = partially completed, Pending = due but not yet reported, - = not due';
        $meta[] = 'Generated by '.trim(Auth::user()->first_name.' '.Auth::user()->surname).' on '.now()->format('d M Y H:i');

        return Excel::download(
            new EngineeringTableExport('CHOP Monitoring & Evaluation', $headings, $rows, $meta, $fills),
            'chop-monitoring-'.now()->format('Ymd-His').'.xlsx'
        );
    }

    public function exportPdf()
    {
        $this->authorizeExport();

        return ChopReportPdfController::monitoringPdf($this->report())->download('chop-monitoring-'.now()->format('Ymd'));
    }

    public function render()
    {
        $report = $this->report();
        $selectedFY = $report->financialYear();

        return view('livewire.chop.monitoring-evaluation', [
            'activities' => $report->query()->paginate(20),
            'financialYears' => FinancialYear::active()->orderBy('start_date', 'desc')->get(),
            'categories' => chopcategoryarea::orderBy('name')->get(),
            'months' => MonitoringReport::months($selectedFY),
            'selectedFY' => $selectedFY,
            'stats' => $report->stats(),
            'frequencyOptions' => chopactivities::getFrequencyOptions(),
            'pdfFilters' => $report->toArray(),
        ]);
    }
}
