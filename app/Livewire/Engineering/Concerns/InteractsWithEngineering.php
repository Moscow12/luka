<?php

namespace App\Livewire\Engineering\Concerns;

use App\Exports\EngineeringTableExport;
use App\Services\Engineering\EngineeringActionException;
use App\Support\Engineering\Eng;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Str;
use Maatwebsite\Excel\Facades\Excel;
use Symfony\Component\HttpFoundation\BinaryFileResponse;

/**
 * Shared by engineering screens: run a service action with user-facing feedback, and
 * export the current table to Excel.
 */
trait InteractsWithEngineering
{
    /** Runs a service action; a refused business rule becomes an error message, not a crash. */
    protected function attempt(callable $action, ?string $success = null): bool
    {
        try {
            $action();
        } catch (EngineeringActionException $e) {
            session()->flash('error', $e->getMessage());

            return false;
        }

        if ($success) {
            session()->flash('success', $success);
        }

        return true;
    }

    /**
     * @param  array<int, string>  $headings
     * @param  iterable<int, array<int, mixed>>  $rows
     * @param  array<string, ?string>  $filters  label => value, blank values are left out
     * @param  array<int, array<int, string>>  $fills
     */
    protected function exportTable(string $title, array $headings, iterable $rows, array $filters = [], array $fills = []): BinaryFileResponse
    {
        $meta = collect($filters)->filter(fn ($value) => filled($value))->map(fn ($value, $label) => "{$label}: {$value}")->values()->all();
        $meta[] = 'Generated by '.Auth::user()->full_name.' on '.Eng::dt(now());

        return Excel::download(
            new EngineeringTableExport($title, $headings, collect($rows)->values()->all(), $meta, $fills),
            Str::slug($title).'-'.Eng::now()->format('Ymd-Hi').'.xlsx',
        );
    }
}
